/** Traducteur pour une langue : t('rsvp.deadline', { date }) ; repli français, puis la clé. */
export function translator(lang) {
  const d = DICT[lang] || DICT.fr
  return (key, vars) => {
    const s = d[key] ?? DICT.fr[key] ?? key
    return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? '')) : s
  }
}

